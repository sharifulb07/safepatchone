// A private staging tree is copied with handle-relative source reads. os.Root
// prevents raced symlinks from redirecting reads outside the authorized source.
// Static symlinks, devices and other special files are rejected outright.
type workspace struct {
	base            *os.Root
	name, directory string
}

func snapshot(ctx context.Context, base, source string, limits verification.ExecutionLimits) (*workspace, error) {
	if !filepath.IsAbs(base) || !filepath.IsAbs(source) {
		return nil, verification.ErrUnsafeWorkspace
	}
	if rel, err := filepath.Rel(source, base); err != nil || rel == "." || (rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))) {
		return nil, verification.ErrUnsafeWorkspace
	}
	root, err := openRootNoLinks(source)
	if err != nil {
		return nil, verification.ErrUnsafeWorkspace
	}
	defer root.Close()
	dir, err := os.MkdirTemp(base, "safepatch-run-")
	if err != nil {
		return nil, verification.ErrRunnerUnavailable
	}
	parent, err := openRootNoLinks(base)
	if err != nil {
		_ = os.Remove(dir)
		return nil, verification.ErrRunnerUnavailable
	}
	w := &workspace{base: parent, name: filepath.Base(dir), directory: filepath.Join(dir, "input")}
	if err := parent.Mkdir(w.name+"/input", 0755); err != nil {
		_ = w.close()
		return nil, verification.ErrRunnerUnavailable
	}
	destination, err := parent.OpenRoot(w.name + "/input")
	if err != nil {
		_ = w.close()
		return nil, verification.ErrRunnerUnavailable
	}
	var entries, total int64
	copyEntry := func(name string) error {
		if err := ctx.Err(); err != nil {
			return err
		}
		if name == "." {
			return nil
		}
		entries++
		if entries > limits.InputEntries {
			return verification.ErrInputLimit
		}
		if !verification.ValidWorkingDirectory(name) {
			return verification.ErrUnsafeWorkspace
		}
		info, err := root.Lstat(name)
		if err != nil || info.Mode()&os.ModeSymlink != 0 || (!info.IsDir() && !info.Mode().IsRegular()) {
			return verification.ErrUnsafeWorkspace
		}
		if info.IsDir() {
			return destination.Mkdir(name, 0755)
		}
		if info.Size() > limits.InputBytes-total {
			return verification.ErrInputLimit
		}
		input, err := root.OpenFile(name, sourceOpenFlags, 0)
		if err != nil {
			return verification.ErrUnsafeWorkspace
		}
		defer input.Close()
		actual, err := input.Stat()
		if err != nil || !actual.Mode().IsRegular() || !os.SameFile(info, actual) {
			return verification.ErrUnsafeWorkspace
		}
		mode := fs.FileMode(0644)
		if info.Mode()&0111 != 0 {
			mode = 0755
		}
		output, err := destination.OpenFile(name, os.O_CREATE|os.O_EXCL|os.O_WRONLY, mode)
		if err != nil {
			return verification.ErrUnsafeWorkspace
		}
		// Bound growth after Stat as well as the original size; cancellation is
		// checked on every read rather than waiting for a large file to finish.
		count, err := io.Copy(output, io.LimitReader(contextReader{ctx, input}, limits.InputBytes-total+1))
		err = errors.Join(err, output.Close())
		total += count
		if total > limits.InputBytes {
			return verification.ErrInputLimit
		}
		return err
	}
	// Read directories in bounded batches; WalkDir reads a whole hostile
	// directory before the entry bound could be enforced.
	var walk func(string, int) error
	walk = func(name string, depth int) error {
		if depth > 128 {
			return verification.ErrInputLimit
		}
		dir, err := root.OpenFile(name, sourceOpenFlags, 0)
		if err != nil {
			return verification.ErrUnsafeWorkspace
		}
		defer dir.Close()
		for {
			if err := ctx.Err(); err != nil {
				return err
			}
			batch, readErr := dir.ReadDir(32)
			for _, entry := range batch {
				child := entry.Name()
				if name != "." {
					child = name + "/" + child
				}
				if err := copyEntry(child); err != nil {
					return err
				}
				if entry.IsDir() {
					if err := walk(child, depth+1); err != nil {
						return err
					}
				}
			}
			if readErr == io.EOF {
				return nil
			}
			if readErr != nil {
				return verification.ErrUnsafeWorkspace
			}
		}
	}
	err = walk(".", 0)
	closeErr := destination.Close()
	if err == nil {
		err = closeErr
	}
	if err != nil {
		return nil, errors.Join(err, w.close())
	}
	return w, nil
}

type contextReader struct {
	ctx    context.Context
	reader io.Reader
}

func (r contextReader) Read(p []byte) (int, error) {
	if err := r.ctx.Err(); err != nil {
		return 0, err
	}
	return r.reader.Read(p)
}

func (w *workspace) close() error {
	// Name is generated by MkdirTemp, not repository output. Root.RemoveAll is
	// anchored to the original parent and cannot follow a replaced directory out.
	if w == nil || w.base == nil || !strings.HasPrefix(w.name, "safepatch-run-") || filepath.Base(w.name) != w.name {
		return verification.ErrCleanupFailed
	}
	err := w.base.RemoveAll(w.name)
	// Windows can retain a descendant's directory handle briefly after the
	// job reaches zero active processes. Retry only transient sharing/access
	// errors under the same anchored root and a separate cleanup deadline.
	deadline := time.Now().Add(cleanupTimeout)
	for retryCleanup(err) && time.Now().Before(deadline) {
		time.Sleep(10 * time.Millisecond)
		err = w.base.RemoveAll(w.name)
	}
	closeErr := w.base.Close()
	if err != nil || closeErr != nil {
		return &cleanupFailure{cause: errors.Join(err, closeErr)}
	}
	return nil
}

func rejectRootLink(name string) error {
	for current := filepath.Clean(name); ; current = filepath.Dir(current) {
		info, err := os.Lstat(current)
		if err != nil || info.Mode()&os.ModeSymlink != 0 {
			return verification.ErrUnsafeWorkspace
		}
		if filepath.Dir(current) == current {
			return nil
		}
	}
}

// Open one component at a time and verify the opened identity. A symlink
// swapped between Lstat and OpenRoot cannot redirect an authorized path.
func openRootNoLinks(name string) (*os.Root, error) {
	if !filepath.IsAbs(name) {
		return nil, verification.ErrUnsafeWorkspace
	}
	anchor := filepath.VolumeName(name) + string(filepath.Separator)
	root, err := os.OpenRoot(anchor)
	if err != nil {
		return nil, verification.ErrUnsafeWorkspace
	}
	rel, err := filepath.Rel(anchor, filepath.Clean(name))
	if err != nil {
		root.Close()
		return nil, verification.ErrUnsafeWorkspace
	}
	if rel == "." {
		return root, nil
	}
	for _, component := range strings.Split(rel, string(filepath.Separator)) {
		info, err := root.Lstat(component)
		if err != nil || !info.IsDir() || info.Mode()&os.ModeSymlink != 0 {
			root.Close()
			return nil, verification.ErrUnsafeWorkspace
		}
		next, err := root.OpenRoot(component)
		root.Close()
		if err != nil {
			return nil, verification.ErrUnsafeWorkspace
		}
		actual, err := next.Stat(".")
		if err != nil || !os.SameFile(info, actual) {
			next.Close()
			return nil, verification.ErrUnsafeWorkspace
		}
		root = next
	}
	return root, nil
}
